// Real Playground + HTTP/WebSocket/PostgreSQL using the evaluation browser fixture.
(async () => {
  const passed = [];
  const check = (value, message) => { if (!value) throw new Error(message); };
  const wait = async (predicate, label) => { const until = Date.now() + 12000; while (!await predicate()) { if (Date.now() > until) throw new Error('Timed out: ' + label); await new Promise(resolve => setTimeout(resolve, 25)); } };
  const button = label => [...document.querySelectorAll('button')].find(item => item.textContent === label);
  const click = label => { const item = button(label); check(item && !item.disabled, label + ' unavailable'); item.click(); };
  const request = async (path, body) => { const response = await fetch(path, body === undefined ? undefined : { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) }); const data = await response.json(); check(response.ok || data.status === 'error', JSON.stringify(data)); return data; };
  const strategy = async operation => (await fetch((globalThis.automaticControl ?? 'http://127.0.0.1:3076') + '/' + operation)).json();
  const read = id => request('/api/table-sessions/' + id);
  const command = async (id, kind, body = {}) => { const table = await read(id); return request('/api/table-sessions/' + id + '/' + kind, { requestId: crypto.randomUUID(), expectedPokerRevision: table.pokerRevision, ...body }); };
  const settle = () => new Promise(resolve => setTimeout(resolve, 250));
  const transport = body => request('/api/__transport', body);
  const result = () => document.querySelector('.evaluation-result');
  const scored = () => document.querySelector('.analysis-scores');
  const toggle = async enabled => {
    await wait(() => !document.querySelector('input[name="liveAnalysis"]').matches(':disabled'), 'settings control ready');
    const input = document.querySelector('input[name="liveAnalysis"]');
    if (input.checked !== enabled) input.click();
    await wait(() => button('Save analysis settings') && !button('Save analysis settings').disabled, 'changed settings');
    click('Save analysis settings');
    await wait(() => document.querySelector('.trainer-configuration').textContent.includes('Live Analysis: ' + (enabled ? 'On.' : 'Off.')) && !input.matches(':disabled') && button('Save analysis settings').disabled, 'Live Analysis committed');
  };
  await wait(() => document.body.textContent.includes('Local identity ready'), 'identity');
  await strategy('release'); await strategy('hold');
  const previousId = document.querySelector('.session-id')?.textContent;
  click('Create Table Session');
  await wait(() => document.querySelector('.session-id')?.textContent && document.querySelector('.session-id').textContent !== previousId && document.body.textContent.includes('Live updates connected'), 'created connected session');
  const id = document.querySelector('.session-id').textContent;
  const table = await read(id); const human = table.bindings[0].participantId; const bot = table.bindings[1].participantId;
  await command(id, 'seat-participant', { participantId: human, seat: 1 });
  await command(id, 'seat-participant', { participantId: bot, seat: 2 });
  await command(id, 'start-hand');
  await wait(() => button('Fold') && !button('Fold').disabled, 'legal current decision');
  check(!document.querySelector('.evaluation-result'), 'Live Analysis defaults to visible');
  const initial = (await strategy('status')).evaluations;
  await toggle(true);
  await wait(async () => (await strategy('status')).evaluations === initial + 1, 'automatic Live Analysis without explicit inspection');
  check(document.querySelector('.decision-analysis').textContent.includes('Evaluating the Reference Strategy'), 'Live pending state missing');
  check(!button('Fold').disabled, 'Live Analysis blocks legal play');
  passed.push('enabling Live Analysis automatically evaluates the current human decision and leaves play available');
  await toggle(false);
  check(!result() && !document.querySelector('.decision-analysis [role="status"]'), 'Disabled Live Analysis remains visible');
  await strategy('release'); await settle();
  check(!result(), 'Late hidden Live Analysis output returned to the display');
  check((await strategy('status')).evaluations === initial + 1, 'Toggle-off created unnecessary evaluation');
  passed.push('disabling Live Analysis hides pending and late output without cancelling reusable work');
  await toggle(true); await wait(() => result(), 'cached live evaluation');
  check((await strategy('status')).evaluations === initial + 1, 'Toggle-on duplicated matching work');
  await toggle(false); click('Fold');
  await wait(() => scored() && result().textContent.includes('Accepted human action: Fold'), 'automatic accepted scores without inspection');
  check((await strategy('status')).evaluations === initial + 1, 'Automatic scores reran the live evaluation');
  check(![...document.querySelectorAll('button')].some(item => item.textContent === 'Continue'), 'Feedback gate added');
  passed.push('accepted scores appear automatically with Live Analysis off and reuse its evaluation');
  const frames = (await transport()).frames[id];
  const scoreNotice = frames.filter(frame => frame.type === 'analysis-update').at(-1);
  const scorePath = '/api/table-sessions/' + id + '/analysis/' + scoreNotice.requestId;
  const count = (await transport()).requests[scorePath] ?? 0;
  await settle(); check(((await transport()).requests[scorePath] ?? 0) === count, 'Automatic scores poll after completion');
  passed.push('automatic scores reconcile notifications through HTTP without polling');
  await command(id, 'top-up-to', { participantId: human, targetStack: 1000 });
  await command(id, 'set-button', { seat: 1 }); await command(id, 'start-hand');
  await wait(() => button('Fold') && !button('Fold').disabled, 'next explicit Hand');
  await strategy('fail'); click('Fold');
  await wait(() => button('Retry decision analysis'), 'automatic scored failure');
  const failures = (await strategy('status')).evaluations;
  await settle(); check((await strategy('status')).evaluations === failures, 'Automatic failure implicitly restarted');
  await strategy('hold'); click('Retry decision analysis');
  await wait(() => document.querySelector('.decision-analysis').textContent.includes('Evaluating the Reference Strategy'), 'scored retry pending');
  await strategy('release'); await wait(() => scored(), 'scored Retry complete');
  passed.push('automatic scored failures stay readable and explicit Retry preserves the accepted action');
  await command(id, 'top-up-to', { participantId: human, targetStack: 1000 });
  await command(id, 'set-button', { seat: 1 }); await command(id, 'start-hand');
  await wait(() => button('Fold') && !button('Fold').disabled, 'third explicit Hand');
  await strategy('hold'); click('Disconnect live updates');
  await wait(() => document.body.textContent.includes('Live updates disconnected'), 'disconnected tab');
  click('Fold'); await wait(() => document.querySelector('select[name="analysisDecision"]').value === 'hand-3/decision-1' && document.querySelector('.decision-analysis').textContent.includes('Evaluating'), 'accepted target while disconnected');
  await strategy('release'); await settle(); check(!scored(), 'Disconnected consumer received a completion');
  click('Reconnect live updates'); await wait(() => scored() && document.body.textContent.includes('Live updates connected'), 'ready refresh recovers automatic scores');
  passed.push('initial user-channel readiness reconciles scores completed while disconnected');
  check(document.documentElement.scrollWidth <= innerWidth, 'Horizontal overflow');
  return { passed, tableSessionId: id };
})()
