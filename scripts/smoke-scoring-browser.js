// Real Playground + HTTP/WebSocket/PostgreSQL; use evaluation-browser.ts and live-transport.ts.
(async () => {
  const passed = [];
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const wait = async (predicate, label) => { const until = Date.now() + 15000; while (!await predicate()) { if (Date.now() > until) throw new Error('Timed out: ' + label); await new Promise(resolve => setTimeout(resolve, 25)); } };
  const settle = () => new Promise(resolve => setTimeout(resolve, 250));
  const button = label => [...document.querySelectorAll('button')].find(item => item.textContent === label);
  const click = label => { const item = button(label); check(item && !item.disabled, label + ' unavailable'); item.click(); };
  const analyze = async () => { await wait(() => button('Analyze accepted decision') && !button('Analyze accepted decision').disabled, 'accepted control ready'); click('Analyze accepted decision'); };
  const request = async (path, body) => { const response = await fetch(path, body === undefined ? undefined : { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) }); const data = await response.json(); check(response.ok || data.status === 'error', JSON.stringify(data)); return data; };
  const transport = body => request('/api/__transport', body);
  const strategy = async operation => (await fetch((globalThis.scoringControl ?? 'http://127.0.0.1:3066') + '/' + operation)).json();
  const read = id => request('/api/table-sessions/' + id);
  const command = async (id, kind, body = {}) => { const table = await read(id); return request('/api/table-sessions/' + id + '/' + kind, { requestId: crypto.randomUUID(), expectedPokerRevision: table.pokerRevision, ...body }); };
  const select = (name, value) => { const item = document.querySelector('select[name="' + name + '"]'); check(item, name + ' missing'); item.value = value; item.dispatchEvent(new Event('change', { bubbles: true })); };
  const result = () => document.querySelector('.evaluation-result');
  const scored = () => document.querySelector('.analysis-scores');
  const counts = async path => (await transport()).requests[path] ?? 0;
  await wait(() => document.body.textContent.includes('Local identity ready'), 'identity');
  await strategy('hold'); await strategy('release');
  const previousId = document.querySelector('.session-id')?.textContent;
  await wait(() => button('Create Table Session') && !button('Create Table Session').disabled, 'creation control ready');
  click('Create Table Session');
  await wait(() => document.querySelector('.session-id')?.textContent && document.querySelector('.session-id').textContent !== previousId && document.body.textContent.includes('Live updates connected'), 'created connected session');
  const id = document.querySelector('.session-id').textContent;
  const table = await read(id); const human = table.bindings[0].participantId; const bot = table.bindings[1].participantId;
  await command(id, 'seat-participant', { participantId: human, seat: 1 });
  await command(id, 'seat-participant', { participantId: bot, seat: 2 });
  await command(id, 'start-hand');
  await wait(() => button('Evaluate current decision') && !button('Evaluate current decision').disabled, 'current evaluation');
  const initialEvaluations = (await strategy('status')).evaluations;
  click('Evaluate current decision');
  await wait(() => result()?.textContent.includes('Selected concrete action:'), 'evaluation complete');
  check(!scored(), 'Unaccepted action received scores');
  check(result().textContent.includes('Action Probabilities') && result().textContent.includes('Raise-to 40'), 'Underlying output missing');
  passed.push('evaluation output has aggregate probabilities and exact choices, without scores');
  click('Fold');
  await wait(() => document.querySelector('select[name="analysisDecision"] option[value="hand-1/decision-1"]'), 'accepted target');
  select('analysisDecision', 'hand-1/decision-1'); await settle(); await analyze();
  await wait(() => scored()?.textContent.includes('0.250000') && scored().textContent.includes('0.000000'), 'accepted numerical scores');
  check(result().textContent.includes('Accepted human action: Fold'), 'Accepted action missing');
  check((await strategy('status')).evaluations === initialEvaluations + 1, 'Score reran the matching pre-action evaluation');
  passed.push('accepted scores reuse pre-action evaluation');
  const frames = (await transport()).frames[id];
  const evaluationNotice = frames.find(frame => frame.type === 'analysis-update');
  const firstScore = frames.find(frame => frame.type === 'analysis-update' && frame.requestId !== evaluationNotice.requestId);
  check(firstScore && !('scores' in firstScore), 'Score notification missing or contains numerical payload');
  const scorePath = '/api/table-sessions/' + id + '/analysis/' + firstScore.requestId;
  const reads = await counts(scorePath); await settle(); check(await counts(scorePath) === reads, 'Scores poll after completion');
  passed.push('score notifications reconcile HTTP without polling');
  await command(id, 'top-up-to', { participantId: human, targetStack: 1000 });
  await command(id, 'move-participant', { participantId: human, seat: 3 });
  await command(id, 'set-button', { seat: 3 });
  await command(id, 'start-hand');
  await wait(() => button('Fold') && !button('Fold').disabled, 'later legal human decision');
  await analyze(); await wait(() => scored()?.textContent.includes('0.250000'), 'historical score retained');
  check(!button('Fold').disabled, 'Historical analysis blocked current legal play');
  passed.push('historical target remains available during later play');
  await transport({ kind: 'hold', tableSessionId: id, responseKind: 'analysis-read' });
  await analyze(); await wait(async () => (await transport()).held.includes(id + ':analysis-read'), 'held old score read');
  select('referenceStrategy', 'highest-probability'); await settle(); click('Save analysis settings');
  await wait(() => document.querySelector('.trainer-configuration').textContent.includes('Live Analysis: Off.') && button('Save analysis settings').disabled, 'changed reference committed');
  await analyze(); await wait(() => scored() && result().textContent.includes('highest-probability'), 'changed reference score');
  await transport({ kind: 'release', tableSessionId: id, responseKind: 'analysis-read' }); await settle();
  check(result().textContent.includes('highest-probability'), 'Old score response replaced changed reference');
  passed.push('changed reference isolates delayed historical responses');
  const evaluationsBeforeRestart = (await strategy('status')).evaluations;
  await strategy('restart');
  await wait(() => document.body.textContent.includes('Live updates connected'), 'reconnected user channel');
  await wait(() => scored() && result().textContent.includes('highest-probability'), 'persistent score after restart');
  await analyze(); await settle();
  check((await strategy('status')).evaluations === evaluationsBeforeRestart, 'Restart reevaluated successful score');
  passed.push('persistent scored cache survives restart');
  await strategy('fail'); click('Fold');
  await wait(() => document.querySelector('select[name="analysisDecision"] option[value="hand-2/decision-1"]'), 'second accepted target');
  select('analysisDecision', 'hand-2/decision-1'); await settle(); await analyze();
  await wait(() => button('Retry decision analysis'), 'safe scored failure');
  const failures = (await strategy('status')).evaluations; await settle(); check((await strategy('status')).evaluations === failures, 'Failed score implicitly restarted');
  await strategy('hold'); click('Retry decision analysis');
  await wait(() => document.querySelector('.decision-analysis').textContent.includes('Evaluating the Reference Strategy'), 'score retry pending');
  await strategy('release'); await wait(() => scored()?.textContent.includes('0.250000'), 'score retry complete');
  passed.push('explicit scored Retry restores scores without an implicit restart');
  const overflow = document.documentElement.scrollWidth > innerWidth;
  check(!overflow, 'Desktop horizontal overflow');
  return { passed, tableSessionId: id, scores: scored().textContent, evaluations: (await strategy('status')).evaluations };
})()
