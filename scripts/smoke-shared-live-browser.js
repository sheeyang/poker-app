// Run through chrome-devtools-axi against the real app behind live-transport.ts.
(async () => {
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  const wait = async predicate => { const end = Date.now() + 10000; while (!await predicate()) { if (Date.now() > end) throw new Error('Browser condition timed out'); await new Promise(resolve => setTimeout(resolve, 25)); } };
  const button = text => [...document.querySelectorAll('button')].find(element => element.textContent === text);
  const click = text => { const element = button(text); check(element && !element.matches(':disabled'), text + ' unavailable'); element.click(); };
  const request = async (path, body) => { const response = await fetch(path, body ? { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) } : undefined); const data = await response.json(); check(response.ok, JSON.stringify(data)); return data; };
  const transport = body => request('/api/__transport', body);
  await wait(() => document.body.textContent.includes('Local identity ready'));
  await wait(async () => (await transport()).connections.length === 1);
  const initial = await transport();
  check(initial.connections[0].tableSessionIds.length === 0, 'Open app without selected table should retain its user connection');
  const connectionId = initial.connections[0].id;
  const create = async () => { const previous = document.querySelector('.session-id')?.textContent; click('Create Table Session'); await wait(() => document.querySelector('.session-id')?.textContent && document.querySelector('.session-id').textContent !== previous && document.body.textContent.includes('Live updates connected')); return document.querySelector('.session-id').textContent; };
  const first = await create();
  await wait(async () => (await transport()).sockets.includes(first));
  click('Seat Participant');
  await wait(() => document.body.textContent.includes('Poker 1 · Session 1'));
  const second = await create();
  await wait(async () => { const state = await transport(); return state.sockets.includes(second) && !state.sockets.includes(first); });
  let state = await transport();
  check(state.opened === initial.opened && state.connections[0].id === connectionId, 'Table switching replaced the shared socket');
  await transport({ kind: 'replay', tableSessionId: first, revision: 1 });
  check(document.querySelector('.session-id').textContent === second && document.body.textContent.includes('Poker 0 · Session 0'), 'Abandoned table frame leaked into selected view');
  click('Close Table Session');
  await wait(() => !document.querySelector('.session-id'));
  await wait(async () => (await transport()).sockets.length === 0);
  state = await transport();
  check(state.connections.length === 1 && state.connections[0].id === connectionId, 'Closing the table replaced the user connection');
  click(first);
  await wait(() => document.querySelector('.session-id')?.textContent === first && document.body.textContent.includes('Live updates connected') && document.body.textContent.includes('Poker 1 · Session 1'));
  check(document.querySelector('.presentation-events summary').textContent === 'Presentation events received: 0', 'Resubscription replayed events');
  await transport({ kind: 'hold', tableSessionId: first, responseKind: 'read' });
  click('Refresh view');
  await wait(async () => (await transport()).held.includes(first + ':read'));
  await transport({ kind: 'disconnect', tableSessionId: first });
  await wait(async () => { const current = await transport(); return current.connections.length === 1 && current.connections[0].id !== connectionId && current.sockets.includes(first); });
  await wait(() => document.body.textContent.includes('Live updates connected'));
  const table = await request('/api/table-sessions/' + first);
  await request('/api/table-sessions/' + first + '/seat-participant', { requestId: crypto.randomUUID(), expectedPokerRevision: 1, participantId: table.bindings[1].participantId, seat: 2 });
  await wait(() => document.body.textContent.includes('Poker 2 · Session 2'));
  await transport({ kind: 'release', tableSessionId: first, responseKind: 'read' });
  await wait(() => !document.body.textContent.includes('Loading Table Session'));
  check(document.body.textContent.includes('Poker 2 · Session 2'), 'Retired connection HTTP response overwrote reconnect');
  check((await request('/api/table-sessions/' + first)).pokerRevision === 2, 'Connection lifecycle changed poker history');
  return { passed: true, cases: ['one socket without selected table', 'switch retains socket', 'close retains socket', 'resubscribe complete view', 'stale table isolation', 'reconnect restores subscription', 'stale HTTP after reconnect'] };
})
