// Run with chrome-devtools-axi eval against evaluation-browser.ts + live-transport.ts.
// Strategy control defaults to the isolated fixture port; actual HTTP/WS/PostgreSQL stay intact.
(async () => {
  const check = (value, message) => { if (!value) throw new Error(message); };
  const wait = async (predicate, label = 'browser condition') => { const until = Date.now() + 12000; while (!await predicate()) { if (Date.now() > until) throw new Error('Timed out: ' + label); await new Promise(resolve => setTimeout(resolve, 25)); } };
  const settle = () => new Promise(resolve => setTimeout(resolve, 150));
  const button = text => [...document.querySelectorAll('button')].find(element => element.textContent === text);
  const click = text => { const item = button(text); check(item && !item.disabled, text + ' unavailable'); item.click(); };
  const request = async (path, body) => { const response = await fetch(path, body ? { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) } : undefined); const data = await response.json(); check(response.ok || data.status === 'error', JSON.stringify(data)); return data; };
  const transport = body => request('/api/__transport', body);
  const strategy = async operation => (await fetch('http://127.0.0.1:3026/' + operation)).json();
  const read = id => request('/api/table-sessions/' + id);
  const command = async (id, kind, body = {}) => { const table = await read(id); return request('/api/table-sessions/' + id + '/' + kind, { requestId: crypto.randomUUID(), expectedPokerRevision: table.pokerRevision, ...body }); };
  const result = () => document.querySelector('.evaluation-result');
  const counts = async path => (await transport()).requests[path] ?? 0;
  const create = async () => {
    const old = document.querySelector('.session-id')?.textContent;
    click('Create Table Session');
    await wait(() => document.querySelector('.session-id')?.textContent && document.querySelector('.session-id').textContent !== old && document.body.textContent.includes('Live updates connected'), 'new connected table');
    const id = document.querySelector('.session-id').textContent; const table = await read(id);
    await command(id, 'seat-participant', { participantId: table.bindings[0].participantId, seat: 1 });
    await command(id, 'seat-participant', { participantId: table.bindings[1].participantId, seat: 2 });
    await command(id, 'start-hand');
    await wait(() => button('Evaluate current decision') && !button('Evaluate current decision').disabled && button('Fold') && !button('Fold').disabled, 'legal current decision');
    return id;
  };
  await wait(() => document.body.textContent.includes('Local identity ready'));
  const first = await create();
  await strategy('hold'); await transport({ kind: 'hold', tableSessionId: first, responseKind: 'analysis' });
  click('Evaluate current decision');
  await wait(async () => (await transport()).held.includes(first + ':analysis'), 'held initial pending response');
  check(!button('Fold').disabled, 'Held analysis disabled legal play');
  await strategy('release');
  await wait(async () => (await transport()).frames[first]?.some(frame => frame.type === 'analysis-update' && frame.status === 'complete'), 'completion before first pending response');
  await transport({ kind: 'release', tableSessionId: first, responseKind: 'analysis' });
  await wait(() => result()?.textContent.includes('Selected concrete action:'), 'completion reconciled after pending response');
  check(document.querySelector('.evaluation-choices').textContent.includes('Raise-to 40') && document.querySelector('.evaluation-choices').textContent.includes('Raise-to 1000'), 'Exact concrete sizings missing');
  const firstNotice = (await transport()).frames[first].find(frame => frame.type === 'analysis-update');
  const firstPath = '/api/table-sessions/' + first + '/analysis/' + firstNotice.requestId;
  const completedReads = await counts(firstPath);
  await new Promise(resolve => setTimeout(resolve, 650));
  check(await counts(firstPath) === completedReads, 'Normal operation polled analysis');

  const second = await create();
  click('Disconnect live updates'); await wait(() => document.body.textContent.includes('Live updates disconnected'));
  await strategy('hold'); click('Evaluate current decision');
  await wait(() => document.querySelector('.decision-analysis')?.textContent.includes('Evaluating'));
  const pending = await request('/api/table-sessions/' + second + '/analysis', { decisionId: (await read(second)).view.state.decisionId });
  await strategy('release'); await wait(async () => (await request('/api/table-sessions/' + second + '/analysis/' + pending.requestId)).status === 'complete');
  check(!result(), 'Disconnected browser received a completion');
  click('Reconnect live updates');
  await wait(() => result() && document.body.textContent.includes('Live updates connected'), 'initial-ready recovers preconnection success');

  await transport({ kind: 'hold', tableSessionId: second, responseKind: 'analysis-read' });
  click('Evaluate current decision');
  await wait(async () => (await transport()).held.includes(second + ':analysis-read'));
  const oldConnection = (await transport()).connections[0].id;
  await transport({ kind: 'disconnect', tableSessionId: second });
  await wait(async () => { const state = await transport(); return state.connections.length === 1 && state.connections[0].id !== oldConnection && state.sockets.includes(second); }, 'reconnect subscription');
  await transport({ kind: 'release', tableSessionId: second, responseKind: 'analysis-read' });
  await wait(() => result() && !document.querySelector('.decision-analysis [role="status"]'), 'retired fetch reconciles on new connection');

  const third = await create();
  await strategy('hold'); await transport({ kind: 'hold', tableSessionId: third, responseKind: 'analysis' });
  click('Evaluate current decision');
  await wait(async () => (await transport()).held.includes(third + ':analysis'));
  let table = await read(third);
  const oldRequest = await request('/api/table-sessions/' + third + '/analysis', { decisionId: table.view.state.decisionId });
  await request('/api/table-sessions/' + third + '/set-trainer-configuration', { requestId: crypto.randomUUID(), expectedSessionRevision: table.sessionRevision, trainerConfiguration: { liveAnalysis: false, referenceStrategy: { policy: { id: 'uniform-choice', version: 'v1', configuration: {} }, selector: { id: 'highest-probability', version: 'v1', configuration: {} } } } });
  await wait(() => document.querySelector('.trainer-configuration')?.textContent.includes('Committed Reference Strategy: Uniform Choice + Highest Probability Selector') && !button('Evaluate current decision').disabled);
  click('Evaluate current decision');
  await wait(async () => (await transport()).requests['/api/table-sessions/' + third + '/analysis'] >= 2);
  await strategy('release'); await wait(() => result()?.textContent.includes('Selected concrete action: Fold'), 'new reference result');
  const notices = (await transport()).frames[third].filter(frame => frame.type === 'analysis-update');
  check(notices.length === 2, 'Changed reference did not create separate immutable evaluations');
  const oldNotice = notices.find(frame => frame.requestId === oldRequest.requestId);
  check(oldNotice, 'Original immutable request notification missing');
  await transport({ kind: 'release', tableSessionId: third, responseKind: 'analysis' }); await settle();
  check(result()?.textContent.includes('Selected concrete action: Fold'), 'Old pending response replaced new reference result');
  const beforeReplay = { ...(await transport()).requests };
  await transport({ kind: 'replay-analysis', tableSessionId: third, requestId: oldNotice.requestId });
  const currentNotice = notices.find(frame => frame.requestId !== oldRequest.requestId);
  await transport({ kind: 'replay-analysis', tableSessionId: third, requestId: currentNotice.requestId, attemptId: crypto.randomUUID() });
  await settle();
  const afterReplay = (await transport()).requests;
  const currentPath = '/api/table-sessions/' + third + '/analysis/' + currentNotice.requestId;
  for (const path of Object.keys(afterReplay).filter(path => path.includes('/analysis/'))) check(afterReplay[path] === (beforeReplay[path] ?? 0) + (path === currentPath ? 1 : 0), 'Unknown attempt reconciliation count ' + path + ': ' + beforeReplay[path] + ' -> ' + afterReplay[path]);
  check(result()?.textContent.includes('Selected concrete action: Fold'), 'Unknown attempt replaced authoritative output');

  await transport({ kind: 'hold', tableSessionId: third, responseKind: 'analysis-read' }); click('Evaluate current decision');
  await wait(async () => (await transport()).held.includes(third + ':analysis-read'));
  const fourth = await create();
  await transport({ kind: 'release', tableSessionId: third, responseKind: 'analysis-read' }); await settle();
  check(document.querySelector('.session-id').textContent === fourth && !result(), 'Abandoned table response replaced current state');
  await strategy('fail'); click('Evaluate current decision');
  await wait(() => document.querySelector('.decision-analysis [role="alert"]')?.textContent.includes('failed'), 'safe failure display');
  check(!button('Fold').disabled, 'Failed analysis disabled legal play');
  const failedCount = (await strategy('')).evaluations;
  click('Evaluate current decision'); await settle();
  check((await strategy('')).evaluations === failedCount, 'Ordinary error read retried Strategy');
  await command(fourth, 'act', { participantId: (await read(fourth)).bindings[0].participantId, action: { type: 'fold' } });
  await wait(() => button('Evaluate current decision').disabled && !document.querySelector('.decision-analysis [role="alert"]'), 'advance clears old current analysis');
  check((await transport()).connections.length === 1, 'Evaluation added another socket');
  const fifth = await create();
  await strategy('hold'); click('Evaluate current decision');
  await wait(() => document.querySelector('.decision-analysis')?.textContent.includes('Evaluating'));
  const lost = await request('/api/table-sessions/' + fifth + '/analysis', { decisionId: (await read(fifth)).view.state.decisionId });
  await strategy('restart');
  await wait(() => result() && document.body.textContent.includes('Live updates connected'), 'restart replaces missing transient request');
  const recovered = await request('/api/table-sessions/' + fifth + '/analysis', { decisionId: (await read(fifth)).view.state.decisionId });
  check(recovered.status === 'complete' && recovered.requestId !== lost.requestId && recovered.attemptId !== lost.attemptId, 'Restart did not get-or-start genuinely missing work');
  return { passed: true, cases: ['notification during first pending HTTP', 'exact sizing and separate selected action', 'no polling', 'preconnection completion on ready', 'reconnect with old HTTP', 'changed reference isolates late response', 'obsolete request/attempt notification', 'abandoned table response', 'failure preserves legal play', 'ordinary reads do not retry', 'one shared socket', 'restart recovers missing transient request'] };
})
